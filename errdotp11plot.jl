# General parsing function: input a multiline string, return (L_array, p11_array) with BigFloat
function parse_p11_multiline(str::AbstractString)
    L_vals = Int[]
    p11_vals = BigFloat[]
    for line in split(str, '\n')
        line = strip(line)
        isempty(line) && continue
        # Match format: p_11(L=number) = value
        m = match(r"dot\(p\)_11\(L=(\d+)\)\s*=\s*([+-]?\d*\.?\d+(?:[eE][+-]?\d+)?)", line)
        if m !== nothing
            L = parse(Int, m[1])
            val = parse(BigFloat, m[2])  # highest precision
            push!(L_vals, L)
            push!(p11_vals, val)
        end
    end
    return L_vals, p11_vals
end

